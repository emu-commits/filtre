#!/usr/bin/env python3
"""Generate the FILTRE factory loop: an original two-bar disco vamp, CC0.

Everything is synthesised here (FM electric piano, muted guitar, bass, string
pad) - no recording of any existing record is involved. Output:
  factory_loop.cpp                 mu-law array compiled into the firmware
  factory-sd/groovebox/loops/FILTRE-DEMO.wav   the same audio for the SD card
"""
import numpy as np, struct, sys, os

SR, BPM, BARS = 22050, 122, 2
STEP = 60.0 / BPM / 4                      # one 16th, seconds
N = int(round(BARS * 16 * STEP * SR))
t_all = np.arange(N) / SR
out = np.zeros(N)
rng = np.random.default_rng(512)

def hz(semi_from_a4): return 440.0 * 2 ** (semi_from_a4 / 12.0)

def place(sig, step, gain=1.0):
    a = int(round(step * STEP * SR))
    b = min(N, a + len(sig))
    out[a:b] += sig[: b - a] * gain

def epiano(freq, dur, vel=1.0):
    t = np.arange(int(dur * SR)) / SR
    idx = 2.2 * vel * np.exp(-t * 7.0) + 0.25
    body = np.sin(2 * np.pi * freq * t + idx * np.sin(2 * np.pi * freq * t))
    tine = 0.25 * np.sin(2 * np.pi * freq * 4.0 * t) * np.exp(-t * 18.0)
    env = np.exp(-t * 2.6) * np.minimum(1.0, t / 0.003)
    rel = np.minimum(1.0, (dur - t) / 0.03)
    return (body + tine) * env * rel * vel

def chord(notes, dur, vel=1.0):
    return sum(epiano(hz(n), dur, vel) for n in notes) / len(notes)

def guitar(freq, vel=1.0):
    t = np.arange(int(0.09 * SR)) / SR
    pluck = np.sign(np.sin(2 * np.pi * freq * t)) * 0.5 + np.sin(2 * np.pi * freq * 2 * t) * 0.5
    noise = rng.standard_normal(len(t)) * np.exp(-t * 220.0) * 0.6
    return (pluck * np.exp(-t * 55.0) + noise) * vel

def bass(freq, dur, vel=1.0):
    t = np.arange(int(dur * SR)) / SR
    s = np.sin(2 * np.pi * freq * t) + 0.45 * np.sin(4 * np.pi * freq * t) * np.exp(-t * 6)
    env = np.minimum(1.0, t / 0.004) * np.exp(-t * 3.5) * np.minimum(1.0, (dur - t) / 0.02)
    return np.tanh(s * 1.6) * env * vel

# semitones from A4. Bar 1: Am9, bar 2: Fmaj7 -> G6. Classic minor disco vamp.
Am9   = [-12, -9, -5, -2, 2]      # A3 C4 E4 G4 B4
Fmaj7 = [-16, -12, -9, -5]        # F3 A3 C4 E4
G6    = [-14, -10, -7, -5]        # G3 B3 D4 E4

stabs = [  # (step, chord, length in steps, velocity)
    (0, Am9, 2.6, 1.0), (3, Am9, 1.2, 0.7), (6, Am9, 3.0, 0.9), (10, Am9, 1.0, 0.6), (12, Am9, 2.0, 0.85), (14.0, Am9, 1.4, 0.7),
    (16, Fmaj7, 2.6, 1.0), (19, Fmaj7, 1.2, 0.7), (22, Fmaj7, 2.0, 0.9), (24, G6, 2.6, 1.0), (27, G6, 1.2, 0.7), (30, G6, 1.8, 0.9),
]
for step, ch, ln, vel in stabs:
    place(chord(ch, ln * STEP, vel), step, 0.80)

# muted 16th guitar, accents off the beat
for s in range(32):
    if s % 4 == 0: continue
    f = hz(-12 + (0 if s < 16 else (-4 if s < 24 else -2)) + 12)
    place(guitar(f, 0.55 if s % 2 else 0.9), s, 0.16)

# bass: root with an octave pop
roots = {0: -36, 16: -40, 24: -38}       # A1, F1, G1
cur = -36
for s in range(32):
    cur = roots.get(s, cur)
    if s % 8 in (0, 3, 6): place(bass(hz(cur), 1.7 * STEP), s, 0.55)
    if s % 8 == 4:         place(bass(hz(cur + 12), 0.9 * STEP, 0.8), s, 0.45)

# string pad: slow, high, slightly detuned
for bar, notes in enumerate(([3, 7, 10], [3, 7, 8])):          # C5 E5 G5 / C5 E5 F5
    a, b = int(bar * 16 * STEP * SR), int((bar + 1) * 16 * STEP * SR)
    t = t_all[: b - a]
    pad = sum(np.sin(2 * np.pi * hz(n) * t * (1 + d) + 0.3 * np.sin(2 * np.pi * 5.1 * t))
              for n in notes for d in (-0.003, 0.003))
    env = np.minimum(1.0, t / 0.25) * np.minimum(1.0, (t[-1] - t) / 0.15)
    out[a:b] += pad * env * 0.035

# glue: tape-ish saturation, gentle top roll-off, fade the very ends so the loop point is clean
out = np.tanh(out * 1.5)
k = np.array([0.25, 0.5, 0.25]); out = np.convolve(out, k, mode="same")
edge = int(0.004 * SR); ramp = np.linspace(0, 1, edge)
out[:edge] *= ramp; out[-edge:] *= ramp[::-1]
out -= out.mean()
pcm = np.round(out / np.abs(out).max() * 29200).astype(np.int16)

def ulaw(p):
    p = int(p); sign = 0
    if p < 0: p, sign = -p, 0x80
    p = min(p, 32635) + 0x84
    e, mask = 7, 0x4000
    while (p & mask) == 0 and e > 0: e -= 1; mask >>= 1
    return (~(sign | (e << 4) | ((p >> (e + 3)) & 0x0F))) & 0xFF

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
u = bytes(ulaw(p) for p in pcm)
with open(os.path.join(root, "factory_loop.cpp"), "w") as f:
    f.write("// FILTRE factory loop - GENERATED by tools/make_factory_loop.py, do not edit.\n"
            "// Original synthesised audio, CC0. Two bars at 122 BPM, 22.05 kHz mono, mu-law.\n"
            '#include "styles.h"\n\n'
            f"const uint32_t g_factoryLoopFrames = {len(u)};\n"
            "const uint8_t g_factoryLoop[] = {\n")
    for i in range(0, len(u), 24):
        f.write(" " + ",".join(str(b) for b in u[i:i + 24]) + ",\n")
    f.write("};\n")

d = os.path.join(root, "factory-sd", "groovebox", "loops")
os.makedirs(d, exist_ok=True)
with open(os.path.join(d, "FILTRE-DEMO.wav"), "wb") as f:
    data = pcm.tobytes()
    f.write(b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVEfmt " +
            struct.pack("<IHHIIHH", 16, 1, 1, SR, SR * 2, 2, 16) + b"data" + struct.pack("<I", len(data)) + data)
print(f"{len(u)} frames, {len(u)/SR:.3f} s, {len(u)/1024:.1f} KB mu-law")
